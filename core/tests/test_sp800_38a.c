#include "aes_cbc.h"

#include <stdio.h>
#include <string.h>

static int expect_bytes(
    const char *name,
    const uint8_t actual[],
    const uint8_t expected[],
    size_t length
)
{
    if (memcmp(actual, expected, length) == 0) {
        return 0;
    }

    printf("FAIL: %s\n", name);
    return 1;
}

int test_sp800_38a(void)
{
    static const uint8_t key[AES_128_KEY_SIZE] = {
        0x2bU, 0x7eU, 0x15U, 0x16U, 0x28U, 0xaeU, 0xd2U, 0xa6U,
        0xabU, 0xf7U, 0x15U, 0x88U, 0x09U, 0xcfU, 0x4fU, 0x3cU
    };
    static const uint8_t iv[AES_BLOCK_SIZE] = {
        0x00U, 0x01U, 0x02U, 0x03U, 0x04U, 0x05U, 0x06U, 0x07U,
        0x08U, 0x09U, 0x0aU, 0x0bU, 0x0cU, 0x0dU, 0x0eU, 0x0fU
    };
    static const uint8_t plaintext[64] = {
        0x6bU, 0xc1U, 0xbeU, 0xe2U, 0x2eU, 0x40U, 0x9fU, 0x96U,
        0xe9U, 0x3dU, 0x7eU, 0x11U, 0x73U, 0x93U, 0x17U, 0x2aU,
        0xaeU, 0x2dU, 0x8aU, 0x57U, 0x1eU, 0x03U, 0xacU, 0x9cU,
        0x9eU, 0xb7U, 0x6fU, 0xacU, 0x45U, 0xafU, 0x8eU, 0x51U,
        0x30U, 0xc8U, 0x1cU, 0x46U, 0xa3U, 0x5cU, 0xe4U, 0x11U,
        0xe5U, 0xfbU, 0xc1U, 0x19U, 0x1aU, 0x0aU, 0x52U, 0xefU,
        0xf6U, 0x9fU, 0x24U, 0x45U, 0xdfU, 0x4fU, 0x9bU, 0x17U,
        0xadU, 0x2bU, 0x41U, 0x7bU, 0xe6U, 0x6cU, 0x37U, 0x10U
    };
    static const uint8_t expected_ciphertext[64] = {
        0x76U, 0x49U, 0xabU, 0xacU, 0x81U, 0x19U, 0xb2U, 0x46U,
        0xceU, 0xe9U, 0x8eU, 0x9bU, 0x12U, 0xe9U, 0x19U, 0x7dU,
        0x50U, 0x86U, 0xcbU, 0x9bU, 0x50U, 0x72U, 0x19U, 0xeeU,
        0x95U, 0xdbU, 0x11U, 0x3aU, 0x91U, 0x76U, 0x78U, 0xb2U,
        0x73U, 0xbeU, 0xd6U, 0xb8U, 0xe3U, 0xc1U, 0x74U, 0x3bU,
        0x71U, 0x16U, 0xe6U, 0x9eU, 0x22U, 0x22U, 0x95U, 0x16U,
        0x3fU, 0xf1U, 0xcaU, 0xa1U, 0x68U, 0x1fU, 0xacU, 0x09U,
        0x12U, 0x0eU, 0xcaU, 0x30U, 0x75U, 0x86U, 0xe1U, 0xa7U
    };

    uint8_t expanded_key[AES_EXPANDED_KEY_SIZE];
    uint8_t ciphertext[sizeof(plaintext)];
    uint8_t decrypted[sizeof(plaintext)];

    aes_expand_key(key, expanded_key);

    const aes_cbc_status encryption_status = aes_cbc_encrypt_blocks(
        plaintext,
        sizeof(plaintext),
        iv,
        expanded_key,
        ciphertext,
        sizeof(ciphertext)
    );
    const aes_cbc_status decryption_status = aes_cbc_decrypt_blocks(
        expected_ciphertext,
        sizeof(expected_ciphertext),
        iv,
        expanded_key,
        decrypted,
        sizeof(decrypted)
    );

    int failures = 0;
    if (encryption_status != AES_CBC_SUCCESS) {
        printf("FAIL: NIST CBC encryption status\n");
        failures++;
    }
    if (decryption_status != AES_CBC_SUCCESS) {
        printf("FAIL: NIST CBC decryption status\n");
        failures++;
    }
    failures += expect_bytes(
        "NIST SP 800-38A CBC encryption",
        ciphertext,
        expected_ciphertext,
        sizeof(expected_ciphertext)
    );
    failures += expect_bytes(
        "NIST SP 800-38A CBC decryption",
        decrypted,
        plaintext,
        sizeof(plaintext)
    );

    return failures;
}
